"""Exploratory, matrix-free quadratic root and eigenvalue experiments.

Run as python -m scripts.paper_quadratic_frontier --help from the repo root.
Solver failures are inconclusive, never counterexamples to existence.
"""
import argparse
import hashlib
import json
import platform
import time
from datetime import datetime
from zoneinfo import ZoneInfo
from pathlib import Path

import numpy as np
import scipy
from scipy.sparse.linalg import LinearOperator, gmres
import CayleyKernel as CK


def square(x):
    """Quadratic identity; valid at every ordinary real CD level."""
    y = 2*x[0]*x
    y[0] -= np.dot(x, x)
    return y


def square_derivative(x, h):
    y = 2*x[0]*h + 2*h[0]*x
    y[0] -= 2*np.dot(x, h)
    return y


def square_root(w):
    """One square root using the complex subalgebra generated by w."""
    im = np.linalg.norm(w[1:])
    q = np.zeros_like(w)
    if im == 0:
        if w[0] >= 0:
            q[0] = np.sqrt(w[0])
        else:
            q[1] = np.sqrt(-w[0])
        return q
    length = np.hypot(w[0], im)
    # Avoid cancellation when w0 is negative.
    a = np.sqrt((length+w[0])/2) if w[0] >= 0 else im/np.sqrt(2*(length-w[0]))
    q[0], q[1:] = a, w[1:]/(2*a)
    return q


def reference_product(a, b):
    """Independent recursive doubling; intended only for small CPU checks."""
    if len(a) == 1:
        return a*b
    h = len(a)//2
    def bar(x):
        y = -x.copy()
        y[0] = x[0]
        return y
    x, y, u, v = a[:h], a[h:], b[:h], b[h:]
    return np.r_[reference_product(x, u)-reference_product(bar(v), y),
                 reference_product(v, x)+reference_product(y, bar(u))]


class Products:
    """Fixed sparse CPU multipliers or the real GPU multiply() API.

    CPU plans are signed permutations from twist(), not dense multiplication
    matrices. Their cost is linear in dimension for fixed coefficient support.
    """
    def __init__(self, dim, backend):
        self.dim, self.backend = dim, backend
        self.calls = 0
        if backend == 'gpu':
            if CK.cp is None or not CK.loaded():
                raise RuntimeError('GPU mode requires CuPy and a compiled CayleyKernel')
            if CK.cp.cuda.runtime.getDeviceCount() < 1:
                raise RuntimeError('GPU mode requires a CUDA device')

    def full(self, a, b):
        self.calls += 1
        if self.backend == 'gpu':
            return np.asarray(CK.multiply(a, b))
        if self.dim > 256:
            raise ValueError('CPU full-product reference is limited to dimension 256; use GPU')
        return reference_product(a, b)

    def fixed(self, a, left=True):
        if self.backend == 'gpu':
            return (lambda x: self.full(a, x)) if left else (lambda x: self.full(x, a))
        indices = np.arange(self.dim)
        plan = []
        for k in np.flatnonzero(a):
            pairs = ((int(k), int(j)) if left else (int(j), int(k)) for j in indices)
            signs = np.asarray(CK.twist_many(pairs), dtype=np.int8)
            plan.append((a[k], indices ^ k, signs))
        def apply(x):
            out = np.zeros(self.dim)
            for value, destinations, signs in plan:
                out[destinations] += value*signs*x
            return out
        return apply


def newton(f, jac, x, tol=1e-9, maxiter=25, restart=40, cycles=15, line_search=12):
    """Damped Newton/GMRES, retaining residual and iteration diagnostics."""
    x = x.copy()
    history = []
    krylov_iterations = 0
    newton_steps = 0
    def count_krylov(_):
        nonlocal krylov_iterations
        krylov_iterations += 1
    def diagnostics(converged, reason):
        return {"converged": converged, "reason": reason, "residuals": history,
                "iterations": len(history)-1, "newton_steps": newton_steps, "krylov_iterations": krylov_iterations}
    for iteration in range(maxiter+1):
        fx = f(x)
        residual = float(np.linalg.norm(fx))
        history.append(residual)
        if not np.isfinite(residual):
            return x, diagnostics(False, 'nonfinite residual')
        if residual <= tol:
            return x, diagnostics(True, 'residual tolerance')
        if iteration == maxiter:
            break
        newton_steps += 1
        J = LinearOperator((len(x), len(x)), matvec=lambda h: jac(x, h), dtype=np.float64)
        step, info = gmres(J, -fx, rtol=1e-7, atol=tol/10, restart=min(restart, len(x)), maxiter=cycles,
                           callback=count_krylov, callback_type="pr_norm")
        if info < 0 or not np.all(np.isfinite(step)):
            break
        accepted = False
        for power in range(line_search):
            candidate = x + (0.5**power)*step
            if np.linalg.norm(f(candidate)) < residual:
                x, accepted = candidate, True
                break
        if not accepted:
            break
    return x, diagnostics(False, 'Newton/GMRES stalled or budget exhausted')


def continuation(linear, r, sign=1, tol=1e-9):
    """Track from x²+r=0 to x²+L(x)+r=0; no root is planted."""
    x, s, step = sign*square_root(-r), 0.0, 0.25
    trace = []
    while s < 1 and len(trace) < 100:
        target = min(1.0, s+step)
        candidate, info = newton(lambda q: square(q)+target*linear(q)+r,
                                 lambda q, h: square_derivative(q, h)+target*linear(h), x, tol)
        trace.append({'parameter': target, 'accepted': info['converged'],
                      'iterations': len(info['residuals'])-1, 'residual': info['residuals'][-1]})
        if info['converged']:
            x, s, step = candidate, target, min(0.5, step*1.5)
        else:
            step /= 2
            if step < 1/4096:
                break
    return x, {'reached_parameter': s, 'converged': s == 1, 'trace': trace}


def coefficient(rng, dim, support=3):
    a = np.zeros(dim)
    positions = rng.choice(dim, min(dim, support), replace=False)
    a[positions] = rng.normal(size=len(positions))
    return a/max(np.linalg.norm(a), 1e-30)


def encoded(x):
    return {str(i): float(x[i]) for i in np.flatnonzero(x)}


def root_experiment(level, seed, backend, strength, tol):
    dim = 1 << level
    rng = np.random.default_rng(seed)
    P = Products(dim, backend)
    a, b, c = [coefficient(rng, dim) for _ in range(3)]
    left_a, right_b, left_c = P.fixed(a), P.fixed(b, False), P.fixed(c)
    linear = lambda x: strength*(left_a(right_b(x))+left_c(x))
    # Dense independent constant excites the full coordinate space.
    r = rng.normal(size=dim)/np.sqrt(dim)
    records = []
    for sign in (1, -1):
        x, info = continuation(linear, r, sign, tol)
        residual = float(np.linalg.norm(square(x)+linear(x)+r))
        # Full GPU multiplication is independent of the square shortcut.
        direct = float(np.linalg.norm(P.full(x, x)+linear(x)+r)) if backend == 'gpu' or dim <= 256 else None
        success = info['converged'] and residual <= 10*tol and (direct is None or direct <= 10*tol)
        records.append({'initial_sign': sign, 'status': 'root_verified' if success else 'unresolved',
                        'residual': residual, 'direct_product_residual': direct,
                        'root_norm': float(np.linalg.norm(x)), 'root_real_part': float(x[0]),
                        'continuation': info, '_root': x})
    separation = float(np.linalg.norm(records[0]['_root']-records[1]['_root']))
    return {'experiment': 'general_quadratic', 'level': level, 'dimension': dim, 'seed': seed,
            'strength': strength, 'coefficients': {k: encoded(v) for k, v in zip('abc', (a,b,c))},
            'root_separation': separation, 'branches': records, 'full_product_calls': P.calls, '_constant': r}


def eigen_experiment(level, seed, backend, tol, maxiter=25, restart=40, cycles=15, line_search=12):
    """Probe the paper's transformation, then attempt the original equation."""
    dim = 1 << level
    if backend == 'cpu' and dim > 256:
        raise ValueError('Eigen experiment CPU mode requires level <= 8')
    rng = np.random.default_rng(seed)
    P = Products(dim, backend)
    a, b, c, d = [coefficient(rng, dim) for _ in range(4)]
    bi = -b.copy(); bi[0] = b[0]
    bi /= np.dot(b, b)
    B, BI, D, RA = P.fixed(b), P.fixed(bi), P.fixed(d), P.fixed(a, False)
    linear = lambda y: B(RA(BI(y)))-B(D(BI(y)))
    r = -B(c)
    y, info = continuation(linear, r, tol=tol)
    x = BI(y)
    equation = lambda z: P.full(z, B(z))+RA(z)-D(z)-c
    jacobian = lambda z, h: P.full(h, B(z))+P.full(z, B(h))+RA(h)-D(h)
    transformed_residual = float(np.linalg.norm(P.full(y, y)+linear(y)+r))
    original_residual = float(np.linalg.norm(equation(x)))
    repaired, repair = newton(equation, jacobian, x, tol, maxiter, restart, cycles, line_search)
    lam = a+B(repaired)
    eigen_residual = float(np.linalg.norm(c+D(repaired)-P.full(repaired, lam)))
    return {'experiment': 'eigenvalue_extension', 'level': level, 'dimension': dim, 'seed': seed,
            'coefficients': {k: encoded(v) for k,v in zip('abcd',(a,b,c,d))},
            'transformed_converged': info['converged'], 'transformed_residual': transformed_residual,
            'transformation_original_residual': original_residual,
            'inverse_property_defect': float(np.linalg.norm(B(x)-y)),
            'artin_identity_defect': float(np.linalg.norm(B(P.full(x, B(x)))-P.full(B(x), B(x)))),
            'direct_solver': repair, 'eigenpair_residual': eigen_residual,
            'status': 'eigenpair_verified' if eigen_residual <= 10*tol else 'unresolved',
            'full_product_calls': P.calls, '_root': repaired, '_lambda': lam}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--experiment', choices=['roots','eigen'], default='roots')
    parser.add_argument('--backend', choices=['cpu','gpu'], default='cpu')
    parser.add_argument('--levels', default='3,4,5,6')
    parser.add_argument('--samples', type=int, default=2)
    parser.add_argument('--seed', type=int, default=23613)
    parser.add_argument('--strength', type=float, default=0.5)
    parser.add_argument('--tol', type=float, default=1e-9)
    parser.add_argument('--output', type=Path, required=True, help='New directory for JSON and root vectors')
    from scripts.batched_eigen_frontier import add_controls, controls, retry_group
    add_controls(parser)
    parser.add_argument('--maxiter', type=int, default=25, help='Direct Newton iteration budget')
    parser.add_argument('--starts', type=int, default=4)
    args = parser.parse_args()
    if args.solver is None:
        args.solver = "batched" if args.experiment == "eigen" else "individual"
    if min(args.maxiter, args.starts, args.batch_size, args.gmres_restart, args.gmres_cycles, args.line_search) < 1:
        parser.error('iteration and batch controls must be positive')
    if args.solver == 'batched' and args.experiment != 'eigen':
        parser.error('batched solver currently supports the eigen experiment')
    try:
        levels = [int(n) for n in args.levels.split(',')]
    except ValueError:
        parser.error('levels must be comma-separated integers')
    if not levels or any(n < 1 or n > 20 for n in levels):
        parser.error('levels must be between 1 and 20')
    if len(set(levels)) != len(levels):
        parser.error('levels must not contain duplicates')
    if args.samples < 1 or not np.isfinite(args.tol) or args.tol <= 0 or not np.isfinite(args.strength):
        parser.error('samples/tolerance must be positive and numeric options finite')
    if args.experiment == 'eigen' and args.backend == 'cpu' and max(levels) > 8:
        parser.error('CPU eigen experiments are limited to level 8; choose GPU for larger levels')
    if args.output.exists():
        parser.error('output already exists; choose a new directory')
    # Fail before creating output if the requested device cannot run.
    Products(2, args.backend)
    args.output.mkdir(parents=True)
    report = {'configuration': {**vars(args), 'output': str(args.output)},
              'python': platform.python_version(), 'numpy': np.__version__, 'scipy': scipy.__version__,
              'cpu_backend': CK.cpu_backend(), 'date': datetime.now(ZoneInfo('America/Vancouver')).isoformat(),
              'kernel_library': CK.library_path(),
              'source_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
              'batched_source_sha256': hashlib.sha256(Path(__file__).with_name('batched_eigen_frontier.py').read_bytes()).hexdigest(),
              'meaning': 'Finite exploratory evidence; unresolved is not evidence of nonexistence.', 'runs': []}
    for level in levels:
        if args.solver == 'batched':
            started = time.perf_counter()
            group, saved = [], []
            for sample in range(args.samples):
                seed = args.seed + 1000*level + sample
                rng = np.random.default_rng(seed)
                coeff = [coefficient(rng, 1 << level) for _ in range(4)]
                group.append({'level': level, 'dimension': 1 << level, 'seed': seed,
                              'coefficients': {k: encoded(v) for k, v in zip('abcd', coeff)}})
                saved.append(rng.normal(size=1 << level)/np.sqrt(1 << level))
            batch_results, stats = retry_group(group, saved, args.backend, args.starts, args.seed, **controls(args))
            report.setdefault('batch_groups', []).append({'level': level, **stats,
                'elapsed_seconds': time.perf_counter()-started})
            print(f'level {level}: batched group completed in {report["batch_groups"][-1]["elapsed_seconds"]:.2f}s', flush=True)
        for sample in range(args.samples):
            seed = args.seed + 1000*level + sample
            started = time.perf_counter()
            result = batch_results[sample] if args.solver == 'batched' else (root_experiment(level, seed, args.backend, args.strength, args.tol)
                      if args.experiment == 'roots' else eigen_experiment(level, seed, args.backend, args.tol, args.maxiter,
                                            args.gmres_restart, args.gmres_cycles, args.line_search))
            result.setdefault('matrix_id', f'level-{level}-seed-{seed}')
            if args.solver == 'batched':
                result.update(experiment='eigenvalue_extension', solver_mode='batched_direct')
                result['_initial_candidate'] = saved[sample]
            vectors = {}
            for k in list(result):
                if k.startswith('_'):
                    vectors[k[1:]] = result.pop(k)
            for j, branch in enumerate(result.get('branches', [])):
                vectors[f'root_{j}'] = branch.pop('_root')
            filename = f'level-{level}-sample-{sample}.npz'
            np.savez_compressed(args.output/filename, **vectors)
            result.update(vector_file=filename,
                          vector_sha256=hashlib.sha256((args.output/filename).read_bytes()).hexdigest())
            timing_key = 'save_seconds' if args.solver == 'batched' else 'elapsed_seconds'
            result[timing_key] = time.perf_counter()-started
            report['runs'].append(result)
            (args.output/'results.json').write_text(json.dumps(report, indent=2, allow_nan=False)+'\n')
            status = result.get('status') or ', '.join(b['status'] for b in result['branches'])
            print(f'level {level}, sample {sample}: {status} ({timing_key}: {result[timing_key]:.2f}s)', flush=True)

